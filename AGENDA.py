# MAGIC ## Get Started with Databricks for Machine Learning
# MAGIC
# MAGIC In this course, you will learn basic skills that will allow you to use the Databricks Data Intelligence Platform to perform a simple data science and machine learning workflow. You will be given a tour of the workspace, and you will be shown how to work with notebooks. You will explore exploratory data analysis and feature engineering, track and manage models with MLflow, experiment using Databricks Genie Code, and deploy a model with Databricks Model Serving. Finally, the course brings these skills together in a comprehensive lab covering the end-to-end machine learning lifecycle.
# MAGIC
# MAGIC ---
# MAGIC
# MAGIC ## Prerequisites
# MAGIC The content was developed for participants with these skills/knowledge/abilities:
# MAGIC
# MAGIC ### Language Skills
# MAGIC - A beginner-level understanding of Python.
# MAGIC
# MAGIC ### Domain Skills
# MAGIC - Basic understanding of DS/ML concepts (e.g. classification and regression models), common model metrics (e.g. F1-score), and Python libraries (e.g. scikit-learn and XGBoost).
